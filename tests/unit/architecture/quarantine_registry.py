def path_matches_protected(path: str, protected: str) -> bool:
    """True when path is covered by a protected file path or directory prefix entry."""

    norm = path.replace("\\", "/")
    prot = protected.replace("\\", "/")
    if prot.endswith("/"):
        return norm.startswith(prot)
    if "::" in prot:
        return norm == prot
    return norm == prot or norm.startswith(prot + "/")



